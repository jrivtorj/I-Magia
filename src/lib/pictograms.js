const BY_ID = new Map(PICTOGRAMS.map((p) => [p.id, p]));

export function getPictogram(id) {
  return BY_ID.get(id);
}

export function getPictogramsByCategory(category) {
  return PICTOGRAMS.filter((p) => p.category === category);
}

export function buildSentence(sequence) {
  return sequence.map((p) => p.label).join(" ");
}
